    private void btnxacnhanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnxacnhanActionPerformed
        String username = txtUsername.getText().trim();
        String phone = txtPhoneNumber.getText().trim();

        XAuth.user = dao.findById(username);

        if (XAuth.user != null && phone.equals(XAuth.user.getPhoneNumber())) {
            JOptionPane.showMessageDialog(this, "Xác minh thành công. Vui lòng nhập mật khẩu mới.");
            txtNewPassword.setEnabled(true);
            btnDoiMatKhau.setEnabled(true);
        } else {
            JOptionPane.showMessageDialog(this, "Sai tên đăng nhập hoặc số điện thoại.");
        }


    }//GEN-LAST:event_btnxacnhanActionPerformed

    private void btnDoiMatKhauActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDoiMatKhauActionPerformed
       
        if (XAuth.user == null) {
            return;
        }

        String newPassword = new String(txtNewPassword.getPassword()).trim();
        if (newPassword.length() < 4) {
            JOptionPane.showMessageDialog(this, "Mật khẩu phải có ít nhất 4 ký tự.");
            return;
        }

        boolean result = dao.updatePassword(XAuth.user.getUsername(), newPassword);
        if (result) {
            JOptionPane.showMessageDialog(this, "Đổi mật khẩu thành công.");
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Đổi mật khẩu thất bại.");
        }

    }//GEN-LAST:event_btnDoiMatKhauActionPerformed

