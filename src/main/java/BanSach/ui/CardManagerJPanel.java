    @Override
    public void create() {
        cardList.add(getForm());
        fillToTable();
        clear();
    }

    @Override
    public void update() {
        if (currentIndex >= 0) {
            cardList.set(currentIndex, getForm());
            fillToTable();
        }
    }

    @Override
    public void delete() {
        if (currentIndex >= 0) {
            cardList.remove(currentIndex);
            fillToTable();
            clear();
        }
    }

