    @Override
    public void moveFirst() {
        if (!cardList.isEmpty()) {
            currentIndex = 0;
            setForm(cardList.get(currentIndex));
        }
    }

    @Override
    public void movePrevious() {
        if (currentIndex > 0) {
            currentIndex--;
            setForm(cardList.get(currentIndex));
        }
    }

    @Override
    public void moveNext() {
        if (currentIndex < cardList.size() - 1) {
            currentIndex++;
            setForm(cardList.get(currentIndex));
        }
    }

    @Override
    public void moveLast() {
        if (!cardList.isEmpty()) {
            currentIndex = cardList.size() - 1;
            setForm(cardList.get(currentIndex));
        }
    }

