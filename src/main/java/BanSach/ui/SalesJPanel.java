    @Override
    public void onAddToInvoice(Book book, int quantity) {
        if (book == null || quantity <= 0) {
            return;
        }

        // Kiểm tra xem sách đã có trong bảng chưa
        boolean daCo = false;
        for (int i = 0; i < modelHoaDon.getRowCount(); i++) {
            String id = modelHoaDon.getValueAt(i, 0).toString();
            if (id.equals(book.getId())) {
                // Nếu đã có thì cộng dồn số lượng
                int soLuongCu = Integer.parseInt(modelHoaDon.getValueAt(i, 2).toString());
                int soLuongMoi = soLuongCu + quantity;

                modelHoaDon.setValueAt(soLuongMoi, i, 2); // cập nhật số lượng
                modelHoaDon.setValueAt(book.getSalePrice(), i, 3); // giá bán
//                modelHoaDon.setValueAt(soLuongMoi * book.getSalePrice(), i, 4); // thành tiền
                daCo = true;
                break;
            }
        }

        // Nếu chưa có thì thêm mới
        if (!daCo) {
            modelHoaDon.addRow(new Object[]{
                book.getId(),
                book.getName(),
                quantity,
                book.getSalePrice()
//                quantity * book.getSalePrice()
            });
        }

        capNhatTongTien();
    }

    public void hienThiDanhSach(List<Book> ds) {
        pnlDanhSach.removeAll();
        for (Book b : ds) {
            SachPanel sp = new SachPanel(this);
            sp.setBook(b);
            pnlDanhSach.add(sp);
        }
        pnlDanhSach.revalidate();
        pnlDanhSach.repaint();
    }

    public String insertHoaDonVaLayMa() {
        String maHoaDon = null;

        try (Connection conn = XJdbc.openConnection()) {
            String sql = "INSERT INTO Invoice(TotalAmount) VALUES (?)";
            PreparedStatement ps = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);

            double tongTien = tinhTongTien();
            ps.setDouble(1, tongTien);

            int affectedRows = ps.executeUpdate();
            if (affectedRows == 0) {
                System.out.println("⚠️ Không thêm được hóa đơn vào CSDL.");
                return null;
            }

            ResultSet rs = ps.getGeneratedKeys();
            if (rs.next()) {
                int id = rs.getInt(1);
                maHoaDon = "INV" + String.format("%03d", id);
                System.out.println("✅ Mã hóa đơn mới: " + maHoaDon);
            } else {
                System.out.println("⚠️ Không lấy được ID của hóa đơn mới.");
            }

            rs.close();
            ps.close();
        } catch (Exception e) {
            e.printStackTrace();
        }

        return maHoaDon;
    }

    public double tinhTongTien() {
        double tongTien = 0;
        for (int i = 0; i < modelHoaDon.getRowCount(); i++) {
            int soLuong = Integer.parseInt(modelHoaDon.getValueAt(i, 2).toString());
            double giaBan = Double.parseDouble(modelHoaDon.getValueAt(i, 3).toString());
            tongTien += soLuong * giaBan;
        }
        return tongTien;
    }

    public void insertChiTietHoaDon(String maHoaDon, DefaultTableModel model) {
        try {
            Connection conn = XJdbc.openConnection();

            String sql = "INSERT INTO InvoiceDetail (InvoiceCode, BookID, Quantity, Price) VALUES (?, ?, ?, ?)";
            PreparedStatement ps = conn.prepareStatement(sql);

            for (int i = 0; i < model.getRowCount(); i++) {
                String bookId = model.getValueAt(i, 0).toString(); // mã sách
                int quantity = Integer.parseInt(model.getValueAt(i, 2).toString()); // số lượng
                double price = Double.parseDouble(model.getValueAt(i, 3).toString()); // đơn giá

                ps.setString(1, maHoaDon);
                ps.setString(2, bookId);
                ps.setInt(3, quantity);
                ps.setDouble(4, price);

                ps.addBatch();
            }

            ps.executeBatch();
            ps.close();
            conn.close();

            System.out.println("Đã lưu chi tiết hóa đơn.");
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

